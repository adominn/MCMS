// Writes the gallery appendices of the UI/UX spec from the capture manifest (tools/gallery.js).
// Usage: node UIUX/v2/tools/specgallery.js <gallery-dir> <src-dir> <img-url-prefix>
const fs = require('fs'), path = require('path');
const [, , gdir, srcDir, prefix] = process.argv;
const M = JSON.parse(fs.readFileSync(path.join(gdir, 'manifest.json'), 'utf8'));
const esc = s => String(s || '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const img = f => `${prefix}/${f}`;
let fig = 0;
const figure = (file, cap, cls = '') => `<figure data-f="g${++fig}" class="gal ${cls}"><img src="${img(file)}"><figcaption>${cap.replace(/([?!.])\.$/, '$1')}</figcaption></figure>\n`; // one closing full stop, never after a question mark
const GROUPS = [['CMN', 'Common and sign-in', 'cmn'], ['PUB', 'Public website', null], ['ST', 'Student', 'st'], ['LEC', 'Lecturer and reviewer', 'lec'], ['EXT', 'Industry expert', 'ext'], ['DD', 'Deputy dean', 'dd'], ['CODL', 'CODL system administrator', 'codl']];
const style = `<style>
  figure.gal img { display:block; max-width:100%; max-height:228mm; margin:0 auto; border:1px solid #c6c6c6; }
  figure.gal.pop img, figure.gal.menu img { max-height:150mm; }
  .flowgrid { display:grid; grid-template-columns:1fr 1fr; gap:8px 12px; margin:6px 0 14px; }
  .flowgrid > div { break-inside:avoid; font-size:8.5pt; line-height:1.35; }
  .flowgrid img { width:100%; border:1px solid #c6c6c6; display:block; margin-bottom:3px; }
  .flowgrid b { font-weight:600; }
  .galh { font-weight:600; font-size:10.5pt; margin:14px 0 4px; break-after:avoid; }
  .galsub { color:#525252; font-size:9pt; margin:0 0 4px; }
</style>\n`;
const count = k => M.filter(m => m.kind === k).length;

// Appendix B: every screen with its tabs, wizard steps and pop-ups, by role
let b = `<!-- generated by UIUX/v2/tools/specgallery.js from the capture manifest; do not edit by hand -->\n${style}<h1>Appendix B. Screen Gallery</h1>
<p>Every screen of the approved prototype, captured from the prototype with its sample data: ${count('screen')} screens, followed on the same page by each screen's other tabs and wizard steps (${count('state')} states) and every pop-up, warning and side panel it opens (${count('popup')}). The menus of each role (${count('menu')}) close each role's section. Screen IDs and routes match Section 6.6. Pop-ups that only appear for a record in a particular state were captured with that state set, for example Endorse after every blocking comment is resolved.</p>\n`;
GROUPS.forEach(([pre, name, menuRole], gi) => {
  const scr = M.filter(m => m.kind === 'screen' && m.id.startsWith(pre + '-'));
  if (!scr.length) return;
  b += `<h2>B.${gi + 1} ${name}</h2>\n`;
  for (const s of scr) {
    b += `<p class="galh">${s.id} ${esc(s.title)}</p><p class="galsub"><code>${esc(s.route)}</code></p>\n`;
    b += figure(s.file, `${s.id} ${esc(s.title)}.`);
    M.filter(m => m.kind === 'state' && m.id === s.id).forEach(st => { b += figure(st.file, `${s.id} ${esc(s.title)}: ${esc(st.label)}.`); });
    M.filter(m => m.kind === 'popup' && m.id === s.id).forEach(p => { b += figure(p.file, `${s.id} ${esc(p.label.replace(/^Confirmation: (?!.*\?$)/, 'Dialog: '))}.`, 'pop'); });
  }
  // pop-ups captured from a prepared record state carry the group prefix only
  M.filter(m => m.kind === 'popup' && m.id === pre).forEach(p => { b += `<p class="galh">${esc(p.title)}</p>\n` + figure(p.file, `${esc(p.label.replace(/^Confirmation: (?!.*\?$)/, 'Dialog: '))} (record state: ${esc(p.title)}).`, 'pop'); });
  if (menuRole) M.filter(m => m.kind === 'menu' && m.id === menuRole).forEach(m => { b += figure(m.file, `${name}: ${esc(m.title)}.`, 'menu'); });
});
// pop-ups opened from the shared shell (idle sign-out, sign out)
M.filter(m => m.kind === 'popup' && m.id === 'CMN').forEach(p => { b += figure(p.file, `Shell: ${esc(p.label)}.`, 'pop'); });

// Appendix C: every page of every printable document
let c = `<!-- generated by UIUX/v2/tools/specgallery.js; do not edit by hand -->\n<h1>Appendix C. Printable Document Gallery</h1>
<p>Every page of every printable document and report template of Section 8 (${count('docpage')} pages), as the user prints it or saves it as PDF. Documents use sample data; the report template is shown for the "credentials issued" report and lays out the other nine reports the same way.</p>\n`;
const docs = [...new Set(M.filter(m => m.kind === 'docpage' || (m.kind === 'screen' && m.id.startsWith('DOC-'))).map(m => m.id))];
docs.forEach(id => {
  const pages = M.filter(m => (m.kind === 'docpage' || m.kind === 'screen') && m.id === id);
  c += `<p class="galh">${id} ${esc(pages[0].title)}</p><p class="galsub"><code>${esc(pages[0].route)}</code></p>\n`;
  pages.forEach(p => { c += figure(p.file, `${id} ${esc(p.title)}${p.label ? ', ' + esc(p.label.toLowerCase()) : ''}.`); });
});

// Appendix D: storyboard of every flow, every step
let d = `<!-- generated by UIUX/v2/tools/specgallery.js; do not edit by hand -->\n<h1>Appendix D. Flow Storyboards</h1>
<p>Every step of every flow of Section 7 (${new Set(M.filter(m => m.kind === 'flowstep').map(m => m.id)).size} flows, ${count('flowstep')} steps), as the prototype shows it with the step bar at the bottom. Read each flow left to right, top to bottom; the text under each picture is the step bar's explanation.</p>\n`;
const flows = [...new Set(M.filter(m => m.kind === 'flowstep').map(m => m.id))];
flows.forEach((id, i) => {
  const steps = M.filter(m => m.kind === 'flowstep' && m.id === id);
  d += `<h2>D.${i + 1} ${id} ${esc(steps[0].title)}</h2>\n<p class="galsub">${esc(steps[0].actor || '')} · ${steps.length} steps</p>\n<div class="flowgrid">\n`;
  steps.forEach(s => { d += `<div><img src="${img(s.file)}"><b>${esc(s.label)}.</b> ${esc(s.say)} <span style="color:#525252">(<code>${esc(s.route)}</code>)</span></div>\n`; });
  d += '</div>\n';
});
d += '</main>\n';
fs.writeFileSync(path.join(srcDir, '12-appendix-b.html'), b, 'utf8');
fs.writeFileSync(path.join(srcDir, '13-appendix-c.html'), c, 'utf8');
fs.writeFileSync(path.join(srcDir, '14-appendix-d.html'), d, 'utf8');
console.log(`figures ${fig}; flow steps ${count('flowstep')}`);
