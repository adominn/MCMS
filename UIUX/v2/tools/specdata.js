// Writes the screen inventory and flow catalogue of the prototype as spec fragments (tbl scripts for the document template).
// Usage: node UIUX/v2/tools/specdata.js <inventory.html> <flows.html>   (server on http://localhost:8731)
const path = require('path');
const fs = require('fs');
const { execSync } = require('child_process');
const pwc = process.env.PWC || path.join(execSync('npm root -g').toString().trim(), '@playwright', 'cli', 'node_modules', 'playwright-core');
const { chromium } = require(pwc);
const [, , invOut, flowOut] = process.argv;

(async () => {
  const browser = await chromium.launch({ channel: 'msedge' });
  const page = await browser.newPage();
  await page.goto('http://localhost:8731/'); await page.evaluate(() => sessionStorage.clear()); await page.goto('http://localhost:8731/#/');
  const d = await page.evaluate(() => ({
    screens: MC.screens.filter(s => !['screens', 'flows', '404'].includes(s.route)).map(s => ({ route: s.route, title: s.title, role: s.route.startsWith('public') ? 'public' : s.route.startsWith('doc') ? 'doc' : (s.role || '') })),
    flows: MC.flows.map(f => ({ id: f.id, title: f.title, actor: f.actor || '', steps: f.steps.length, summary: f.summary || '' })),
  }));
  await browser.close();
  const clean = t => String(t).replace(/\|/g, '/').replace(/\s+/g, ' ').trim();
  const GROUPS = [['', 'Common and sign-in', 'cmn'], ['public', 'Public website', 'pub'], ['st', 'Student (P8)', 'st'], ['lec', 'Lecturer (P1)', 'lec'], ['ext', 'Industry expert (X2)', 'ext'],
    ['dd', 'Deputy dean (P2)', 'dd'], ['codl', 'CODL system administrator (S1/P5)', 'codl'], ['doc', 'Printable documents', 'doc']];
  let inv = '<!-- generated by UIUX/v2/tools/specdata.js from the approved prototype; do not edit by hand -->\n'
    + `<h2>6.6 Screen Inventory</h2>\n<p>The ${d.screens.length} screens of the approved prototype, by role. The ID is used in tests and in the SDD; the route opens the screen in the prototype with sample data. Routes with a <code>:</code> take a record identifier.</p>\n`;
  for (const [k, label, key] of GROUPS) {
    const rows = d.screens.filter(s => s.role === k);
    if (!rows.length) continue;
    inv += `<h3>${label}</h3>\n<p class="tcap" data-t="inv-${key}">Screens for ${label} (${rows.length})</p>\n<script type="text/tbl" data-h="ID|Screen|Route" data-w="12%|46%|42%" data-cls="small">\n`;
    rows.forEach((s, i) => { inv += `${key.toUpperCase()}-${String(i + 1).padStart(2, '0')} | ${clean(s.title)} | <code>#/${s.route}</code>\n`; });
    inv += '</script>\n';
  }
  fs.writeFileSync(invOut, inv, 'utf8');
  let fl = '<!-- generated by UIUX/v2/tools/specdata.js from the approved prototype; do not edit by hand -->\n<p class="tcap" data-t="flows">Walk-through flows in the prototype</p>\n<script type="text/tbl" data-h="ID|Flow|Actors|Steps" data-w="10%|56%|24%|10%" data-cls="small">\n';
  d.flows.sort((a, b) => a.id.localeCompare(b.id, 'en', { numeric: true })).forEach(f => { fl += `${f.id} | <b>${clean(f.title)}</b>${f.summary ? '. ' + clean(f.summary) : ''} | ${clean(f.actor)} | ${f.steps}\n`; });
  fl += '</script>\n';
  fs.writeFileSync(flowOut, fl, 'utf8');
  console.log(`${d.screens.length} screens, ${d.flows.length} flows`);
})();
