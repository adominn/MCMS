// ---- discrepancies and corrections (FR-mismatch, FR-correct, BR-38)

it('logs each mismatch once and resolves it only through a correction that keeps the original (FR-mismatch, FR-correct)', function () {
    $dep = deposited();
    DB::table('acrs')->where('id', $dep->acr_id)->update(['credits' => 2]); // the credential says 3
    DB::table('abc_deposits')->where('id', $dep->id)->update(['credits' => 3]);
    expect(app(Discrepancies::class)->scan())->toBeGreaterThanOrEqual(2)->and(app(Discrepancies::class)->scan())->toBe(0);
    $d = DB::table('discrepancies')->where('kind', 'credit_mismatch')->first();
    expect($d->status)->toBe('open')->and($d->description)->toContain('credential');
    $this->actingAs($this->hakim)->post("/records/discrepancies/{$d->id}/resolve", ['reason' => 'Typed wrongly', 'action' => 'ACR credit restored'])->assertSessionHasErrors('source_checked');
    $this->post("/records/discrepancies/{$d->id}/resolve", ['reason' => 'Typed wrongly', 'action' => 'ACR credit restored to 3', 'source_checked' => 1])->assertSessionHasNoErrors();
    $c = DB::table('corrections')->where('discrepancy_id', $d->id)->first();
    expect(DB::table('discrepancies')->find($d->id)->status)->toBe('resolved')->and(json_decode($c->original, true)['discrepancy'])->toContain('credential')->and($c->approver_id)->toBe($this->hakim->id)->and((bool) $c->source_checked)->toBeTrue()
        ->and(DB::table('audit_events')->where('action', 'correction.recorded')->exists())->toBeTrue()
        ->and(DB::table('notifications')->where('user_id', $this->amir->id)->where('template_key', 'correction.recorded')->where('channel', 'in_system')->exists())->toBeTrue();
    $this->post("/records/discrepancies/{$d->id}/resolve", ['reason' => 'x', 'action' => 'y', 'source_checked' => 1])->assertStatus(422);
});

it('logs a completion without a valid credential, and keeps other faculties out of the log (FR-mismatch)', function () {
